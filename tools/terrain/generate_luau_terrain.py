#!/usr/bin/env python3
"""
DGX-04: Generates deterministic Roblox Luau terrain modules from `content/terrain/manifests/source-registry.json`.
Outputs:
- `apps/roblox/src/shared/TerrainData.luau`: Authoritative DEM heightgrids, material grids, CRS metadata, and provenance for all 21 locations across 11 countries.
"""

import os
import json

ROOT = "/home/wael/Code/Miraverse"
REGISTRY_PATH = os.path.join(ROOT, "content/terrain/manifests/source-registry.json")
OUT_LUAU_PATH = os.path.join(ROOT, "apps/roblox/src/shared/TerrainData.luau")


def format_luau_num_array_2d(grid):
    rows = []
    for r in grid:
        vals = ", ".join(f"{v:.2f}" for v in r)
        rows.append(f"\t\t\t{{ {vals} }}")
    return "{\n" + ",\n".join(rows) + "\n\t\t}"


def format_luau_str_array_2d(grid):
    rows = []
    for r in grid:
        vals = ", ".join(f'"{v}"' for v in r)
        rows.append(f"\t\t\t{{ {vals} }}")
    return "{\n" + ",\n".join(rows) + "\n\t\t}"


def main():
    with open(REGISTRY_PATH, "r", encoding="utf-8") as f:
        reg = json.load(f)

    lines = [
        "--!strict",
        "-- GENERATED BY tools/terrain/generate_luau_terrain.py (DGX-04) — DO NOT MANUALLY INVENT ELEVATIONS",
        "-- Source: Copernicus DEM GLO-30 & Mapzen Terrain Tiles (SRTM/GMTED2010/ETOPO1)",
        "local TerrainData = {}",
        "",
        "export type ControlPoint = {",
        "\tname: string,",
        "\tlat: number,",
        "\tlon: number,",
        "\tmeasuredElevationMeters: number,",
        "\tpass: boolean,",
        "}",
        "",
        "export type TerrainRecord = {",
        "\tsourceId: string,",
        "\tlocationId: string,",
        "\tcountryId: string,",
        "\tcountryName: string,",
        "\tdisplayName: string,",
        "\tlocationType: string,",
        "\tgeographicSetting: string,",
        "\tliteraryNote: string?,",
        "\tdetailLevel: number,",
        "\tdataset: string,",
        "\tversion: string,",
        "\tsourceUrl: string,",
        "\tlicense: string,",
        "\tattribution: string,",
        "\tcoordinateReferenceSystem: string,",
        "\tverticalDatum: string,",
        "\thorizontalResolution: string,",
        "\televationUnits: string,",
        "\tchecksum: string,",
        "\tboundingBox: { minLon: number, minLat: number, maxLon: number, maxLat: number },",
        "\televationStatsMeters: { min: number, max: number, mean: number, seaOrBaseLevel: number },",
        "\thorizontalScaleMetersPerStud: number,",
        "\tverticalExaggeration: number,",
        "\tbaseGameY: number,",
        "\tmaxReliefStuds: number,",
        "\twaterFeature: string,",
        "\twaterType: string,",
        "\twaterDirection: string,",
        "\tbiome: string,",
        "\tgridSize: number,",
        "\tgrid16ElevationMeters: { { number } },",
        "\tgrid16GameStudsY: { { number } },",
        "\tgrid16Materials: { { string } },",
        "}",
        "",
        "TerrainData.RECORDS = {",
    ]

    for src in reg["sources"]:
        loc_id = src["locationId"]
        bb = src["boundingBox"]
        st = src["elevationStatsMeters"]
        gm = src["gameMapping"]
        lit_note = f'"{src["literaryNote"]}"' if src.get("literaryNote") else "nil"
        elev_grid_str = format_luau_num_array_2d(src["grid16ElevationMeters"])
        stud_grid_str = format_luau_num_array_2d(src["grid16GameStudsY"])
        mat_grid_str = format_luau_str_array_2d(src["grid16Materials"])

        lines.extend([
            f"\t{loc_id} = {{",
            f'\t\tsourceId = "{src["sourceId"]}",',
            f'\t\tlocationId = "{loc_id}",',
            f'\t\tcountryId = "{src["countryId"]}",',
            f'\t\tcountryName = "{src["countryName"]}",',
            f'\t\tdisplayName = "{src["displayName"]}",',
            f'\t\tlocationType = "{src["locationType"]}",',
            f'\t\tgeographicSetting = "{src["geographicSetting"]}",',
            f"\t\tliteraryNote = {lit_note},",
            f'\t\tdetailLevel = {src["detailLevel"]},',
            f'\t\tdataset = "{src["dataset"]}",',
            f'\t\tversion = "{src["version"]}",',
            f'\t\tsourceUrl = "{src["sourceUrl"]}",',
            f'\t\tlicense = "{src["license"]}",',
            f'\t\tattribution = "{src["attribution"]}",',
            f'\t\tcoordinateReferenceSystem = "{src["coordinateReferenceSystem"]}",',
            f'\t\tverticalDatum = "{src["verticalDatum"]}",',
            f'\t\thorizontalResolution = "{src["horizontalResolution"]}",',
            f'\t\televationUnits = "{src["elevationUnits"]}",',
            f'\t\tchecksum = "{src["checksum"]}",',
            f'\t\tboundingBox = {{ minLon = {bb["minLon"]}, minLat = {bb["minLat"]}, maxLon = {bb["maxLon"]}, maxLat = {bb["maxLat"]} }},',
            f'\t\televationStatsMeters = {{ min = {st["min"]}, max = {st["max"]}, mean = {st["mean"]}, seaOrBaseLevel = {st["seaOrBaseLevel"]} }},',
            f'\t\thorizontalScaleMetersPerStud = {gm["horizontalScaleMetersPerStud"]},',
            f'\t\tverticalExaggeration = {gm["verticalExaggeration"]},',
            f'\t\tbaseGameY = {gm["baseGameY"]},',
            f'\t\tmaxReliefStuds = {gm["maxReliefStuds"]},',
            f'\t\twaterFeature = "{gm["waterFeature"]}",',
            f'\t\twaterType = "{gm["waterType"]}",',
            f'\t\twaterDirection = "{gm["waterDirection"]}",',
            f'\t\tbiome = "{gm["biome"]}",',
            "\t\tgridSize = 16,",
            f"\t\tgrid16ElevationMeters = {elev_grid_str},",
            f"\t\tgrid16GameStudsY = {stud_grid_str},",
            f"\t\tgrid16Materials = {mat_grid_str},",
            "\t},",
        ])

    lines.extend([
        "} :: { [string]: TerrainRecord }",
        "",
        "-- Legacy compatibility lookup table (TerrainData.DESTINATIONS)",
        "TerrainData.DESTINATIONS = {",
        "\tLB_byblos = TerrainData.RECORDS.byblos,",
        "\tLB_mount_lebanon = TerrainData.RECORDS.mount_lebanon,",
        "\tLB_beirut = TerrainData.RECORDS.beirut,",
        "\tEG_cairo = TerrainData.RECORDS.cairo,",
        "\tEG_alexandria = TerrainData.RECORDS.alexandria,",
        "\tEG_aswan = TerrainData.RECORDS.aswan,",
        "\tIQ_baghdad = TerrainData.RECORDS.baghdad,",
        "\tIQ_erbil = TerrainData.RECORDS.erbil,",
        "\tIQ_basra = TerrainData.RECORDS.basra,",
        "\tKR_jeonju = TerrainData.RECORDS.jeonju,",
        "\tKR_seoul = TerrainData.RECORDS.seoul,",
        "\tKR_busan = TerrainData.RECORDS.busan,",
        "\tFR_lyon = TerrainData.RECORDS.lyon,",
        "\tFR_paris = TerrainData.RECORDS.paris,",
        "\tFR_marseille = TerrainData.RECORDS.marseille,",
        "\tDE_rhine = TerrainData.RECORDS.rhine_valley,",
        "\tCN_wuling = TerrainData.RECORDS.wuling_valley,",
        "\tJP_tohoru = TerrainData.RECORDS.tohoku_waystation,",
        "\tRU_svetloyar = TerrainData.RECORDS.svetloyar,",
        "\tUA_kyiv = TerrainData.RECORDS.kyiv,",
        "\tMA_marrakesh = TerrainData.RECORDS.marrakesh_atlas,",
        "} :: { [string]: TerrainRecord }",
        "",
        "function TerrainData.getRecord(locationId: string): TerrainRecord?",
        "\tif type(locationId) ~= \"string\" then",
        "\t\treturn nil",
        "\tend",
        "\tlocal direct = (TerrainData.DESTINATIONS :: any)[locationId]",
        "\tif direct then",
        "\t\treturn direct",
        "\tend",
        "\tlocal lower = string.lower(locationId)",
        "\tlocal aliases: { [string]: string } = {",
        "\t\ttohoku_route = \"tohoku_waystation\",",
        "\t\tmarrakesh = \"marrakesh_atlas\",",
        "\t}",
        "\tlocal key = aliases[lower] or lower",
        "\treturn TerrainData.RECORDS[key]",
        "end",
        "",
        "TerrainData.get = TerrainData.getRecord",
        "",
        "return TerrainData",
        "",
    ])

    with open(OUT_LUAU_PATH, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Generated {OUT_LUAU_PATH} with {len(reg['sources'])} terrain records.")


if __name__ == "__main__":
    main()
